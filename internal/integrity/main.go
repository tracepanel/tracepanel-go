// Command integrity writes ../../integrity.go: npm's integrity (SHA-512) of each agent platform package of the
// version version.go names, which the SDK checks a downloaded agent against. Run by `go generate` in the module's
// root.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"regexp"
	"strings"
)

var platforms = []string{
	"darwin-arm64", "darwin-x64",
	"linux-x64-gnu", "linux-arm64-gnu", "linux-ia32-gnu", "linux-ppc64-gnu", "linux-s390x-gnu", "linux-riscv64-gnu",
	"linux-x64-musl", "linux-arm64-musl", "linux-ia32-musl", "linux-arm",
	"win32-x64", "win32-ia32", "win32-arm64",
}

func main() {
	source, err := os.ReadFile("version.go")
	if err != nil {
		log.Fatal(err)
	}
	match := regexp.MustCompile(`const Version = "([^"]+)"`).FindSubmatch(source)
	if match == nil {
		log.Fatal("no Version in version.go")
	}
	version := string(match[1])
	var out strings.Builder
	out.WriteString("// Code generated by internal/integrity from the npm registry; DO NOT EDIT.\n\n")
	out.WriteString("package tracepanel\n\n")
	out.WriteString("// integrityVersion is the agent version these checksums are of: AgentVersion, or go generate is due.\n")
	fmt.Fprintf(&out, "const integrityVersion = %q\n\n", version)
	out.WriteString("// agentIntegrity is npm's integrity of each platform's agent package, which a download must match.\n")
	out.WriteString("var agentIntegrity = map[string]string{\n")
	for _, platform := range platforms {
		url := fmt.Sprintf("https://registry.npmjs.org/@tracepanel/agent-%s/%s", platform, version)
		response, err := http.Get(url)
		if err != nil {
			log.Fatal(err)
		}
		var meta struct {
			Dist struct {
				Integrity string `json:"integrity"`
			} `json:"dist"`
		}
		err = json.NewDecoder(response.Body).Decode(&meta)
		response.Body.Close()
		if err != nil || meta.Dist.Integrity == "" {
			log.Fatalf("%s: no integrity (%v)", url, err)
		}
		fmt.Fprintf(&out, "\t%q: %q,\n", platform, meta.Dist.Integrity)
	}
	out.WriteString("}\n")
	source, err = format.Source([]byte(out.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("integrity.go", source, 0o644); err != nil {
		log.Fatal(err)
	}
}
