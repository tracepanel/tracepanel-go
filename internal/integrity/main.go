// Command integrity writes internal/agentbin/integrity.go: the SHA-512 of the agent's binary for each platform, at
// the version AgentVersion names in version.go (or -version), which the SDK checks a downloaded agent against. It is
// the binary's, not its package's, so it holds wherever the binary comes from (npm, a mirror) and for the copy in the
// cache. Read from npm's platform packages, each checked against npm's own integrity first. Run in the module's root
// by `go generate` or `make integrity`, once the agent's version is on npm.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"strings"

	"github.com/tracepanel/tracepanel-go/internal/agentbin"
)

const out = "internal/agentbin/integrity.go"

func main() {
	version := flag.String("version", "", "the agent version (default: AgentVersion in version.go)")
	flag.Parse()
	if *version == "" {
		source, err := os.ReadFile("version.go")
		if err != nil {
			log.Fatal(err)
		}
		match := regexp.MustCompile(`const AgentVersion = "([^"]+)"`).FindSubmatch(source)
		if match == nil {
			log.Fatal("no AgentVersion in version.go")
		}
		*version = string(match[1])
	}
	var text strings.Builder
	text.WriteString("// Code generated by internal/integrity from the npm registry; DO NOT EDIT.\n\n")
	text.WriteString("package agentbin\n\n")
	text.WriteString("// Version is the agent these checksums are of, the one the SDK downloads: AgentVersion once go generate ran\n")
	text.WriteString("// for it.\n")
	fmt.Fprintf(&text, "const Version = %q\n\n", *version)
	text.WriteString("// checksums are the SHA-512 of each platform's agent binary, which a download (and the cached copy) must match.\n")
	text.WriteString("var checksums = map[string]string{\n")
	for _, platform := range agentbin.Platforms {
		fmt.Fprintf(&text, "\t%q: %q,\n", platform, checksum(platform, *version))
	}
	text.WriteString("}\n")
	source, err := format.Source([]byte(text.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(out, source, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%s: the agent %s\n", out, *version)
}

// checksum is the platform's binary's SHA-512, from its npm package, which npm's integrity vouches for.
func checksum(platform, version string) string {
	meta := fmt.Sprintf("https://registry.npmjs.org/@tracepanel/agent-%s/%s", platform, version)
	var described struct {
		Dist struct {
			Integrity string `json:"integrity"`
			Tarball   string `json:"tarball"`
		} `json:"dist"`
	}
	if err := json.Unmarshal(fetch(meta), &described); err != nil || described.Dist.Integrity == "" {
		log.Fatalf("%s: no integrity (%v): is the agent %s on npm yet?", meta, err, version)
	}
	tgz := fetch(described.Dist.Tarball)
	if agentbin.Checksum(tgz) != described.Dist.Integrity {
		log.Fatalf("%s doesn't match npm's integrity", described.Dist.Tarball)
	}
	binary := "package/bin/tracepanel-agent"
	if strings.HasPrefix(platform, "win32-") {
		binary += ".exe"
	}
	file, err := agentbin.Entry(tgz, binary)
	if err != nil {
		log.Fatalf("%s: %v", described.Dist.Tarball, err)
	}
	return agentbin.Checksum(file)
}

func fetch(url string) []byte {
	response, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		log.Fatalf("HTTP %d from %s", response.StatusCode, url)
	}
	data, err := io.ReadAll(response.Body)
	if err != nil {
		log.Fatal(err)
	}
	return data
}
